@app.post("/api/v1/plan")
def generate_candidates():
    """Heuristic logic to generate failure candidates based on the graph"""
    try:
        # Load the graph generated by /map
        with open("graph.json", "r") as f:
            graph = json.load(f)
    except FileNotFoundError:
        return {"error": "graph.json not found. Run /map first."}
        
    import planner
    # Step 1: Code-based generation
    heuristic_list = planner.generate_heuristic_candidates(graph)
    
    # Step 2: Optional LLM Re-rank
    final_plan = planner.llm_rerank(heuristic_list)
    
    return {"status": "success", "candidates": final_plan}

@app.post("/api/v1/plan/adaptive")
def generate_adaptive_plan(last_intent_id: int):
    """Generates an adaptive candidate based on the previous experiment's result"""
    db = SessionLocal()
    try:
        from models import ExperimentIntent, ExperimentResult
        intent = db.query(ExperimentIntent).filter(ExperimentIntent.id == last_intent_id).first()
        result = db.query(ExperimentResult).filter(ExperimentResult.intent_id == last_intent_id).first()
        
        if not intent or not result:
            return {"error": "Previous intent or result not found"}
            
        with open("graph.json", "r") as f:
            graph = json.load(f)
            
        import planner
        adaptive_candidate = planner.generate_adaptive_candidate(
            intent.__dict__, 
            result.__dict__, 
            graph
        )
        return {"status": "success", "candidate": adaptive_candidate}
    finally:
        db.close()

@app.post("/api/v1/inject")
async def inject_fault(req: FaultRequest):
    """Triggered by CLI to start a chaos experiment"""
    from faults.manager import ChaosManager
    chaos_manager = ChaosManager(session_factory=SessionLocal)
    
    res = await chaos_manager.execute_fault(
        fault_type=req.fault_type,
        target=req.target,
        params=req.params or {},
        ttl_seconds=60
    )
    return {"status": "success", "result": res}

@app.post("/api/v1/inject/combined")
async def inject_combined_faults(req: CombinedFaultRequest):
    """Stretch Goal: Run multiple failures together concurrently"""
    import asyncio
    from faults.manager import ChaosManager
    chaos_manager = ChaosManager(session_factory=SessionLocal)
    
    # Schedule all faults concurrently
    tasks = []
    for f in req.faults:
        tasks.append(
            chaos_manager.execute_fault(
                fault_type=f.fault_type,
                target=f.target,
                params=f.params or {},
                ttl_seconds=req.ttl_seconds
            )
        )
    
    results = await asyncio.gather(*tasks, return_exceptions=True)
    
    # Format results
    final_results = []
    for r in results:
        if isinstance(r, Exception):
            final_results.append({"status": "error", "message": str(r)})
        else:
            final_results.append({"status": "success", "result": r})
            
    return {"status": "combined_execution_started", "results": final_results}

