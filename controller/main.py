@asynccontextmanager
async def lifespan(app: FastAPI):
    from heartbeat import HeartbeatManager
    from kill_switch import KillSwitch
    
    hb = HeartbeatManager()
    hb.start_background()
    
    ks = KillSwitch()
    ks.start_background()
    
    yield
    
    hb.stop()
    ks.stop()

app = FastAPI(title="AI Chaos Engine Controller", lifespan=lifespan)

