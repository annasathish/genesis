@app.post("/api/v1/map")
def build_map():
    """Triggers the Dependency Mapper to build graph.json"""
    # Assuming M1 puts the compose file in the parent sandbox dir
    graph = mapper.generate_dependency_graph("../sandbox/docker-compose.yaml")
    return {"message": "Graph generated", "graph": graph}

@app.post("/api/v1/plan")
def generate_candidates():
    """Heuristic logic to generate failure candidates based on the graph"""
    try:
        # Load the graph generated by /map
        with open("graph.json", "r") as f:
            graph = json.load(f)
    except FileNotFoundError:
        return {"error": "graph.json not found. Run /map first."}
        
    import planner
    # Step 1: Code-based generation
    heuristic_list = planner.generate_heuristic_candidates(graph)
    
    # Step 2: Optional LLM Re-rank
    final_plan = planner.llm_rerank(heuristic_list)
    
    return {"status": "success", "candidates": final_plan}

@app.post("/api/v1/plan/adaptive")
def generate_adaptive_plan(last_intent_id: int):
    """Generates an adaptive candidate based on the previous experiment's result"""
    db = SessionLocal()
    try:
        from models import ExperimentIntent, ExperimentResult
        intent = db.query(ExperimentIntent).filter(ExperimentIntent.id == last_intent_id).first()
        result = db.query(ExperimentResult).filter(ExperimentResult.intent_id == last_intent_id).first()
        
        if not intent or not result:
            return {"error": "Previous intent or result not found"}
            
        with open("graph.json", "r") as f:
            graph = json.load(f)
            
        import planner
        adaptive_candidate = planner.generate_adaptive_candidate(
            intent.__dict__, 
            result.__dict__, 
            graph
        )
        return {"status": "success", "candidate": adaptive_candidate}
    finally:
        db.close()

_chaos_manager = None


def get_chaos_manager():
    """One ChaosManager per process, so TTL auto-rollback tasks stay referenced
    (a per-request instance is garbage-collected with its pending TTL task)."""
    global _chaos_manager
    if _chaos_manager is None:
        from faults.manager import ChaosManager
        _chaos_manager = ChaosManager(session_factory=SessionLocal)
    return _chaos_manager


@app.post("/api/v1/inject")
async def inject_fault(fault_type: str, target: str, ttl_seconds: int = 60, params: dict = None):
    """Triggered by CLI to start a chaos experiment"""
    res = await get_chaos_manager().execute_fault(
        target=target,
        fault_type=fault_type,
        params=params or {},
        ttl_seconds=ttl_seconds,
    )
    return {"status": "success", "result": res}

@app.post("/api/v1/rollback/{intent_id}")
async def rollback_fault(intent_id: int):
    """Manual rollback override"""
    res = await get_chaos_manager().rollback(intent_id)
    return {"status": "success", "result": res}

@app.get("/api/v1/intents/active")
async def active_intents():
    return await get_chaos_manager().get_active_intents()
